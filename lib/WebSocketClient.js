// lib/WebSocketClient.js — Generates the actor-based WebSocket client

const { derivePackageName, prefixedName, setTypePrefix, setAllowNameCollisions, setPerspective, clientDirection, swiftStringEscape } = require('../helpers/swift');
const { buildServerURL, extractMessages } = require('../helpers/schema');

function WebSocketClient({ asyncapi, params }) {
  setTypePrefix(params?.typePrefix);
  const useMsgpack = params.serialization === 'msgpack';
  if (params?.helpersModule) return renderSpecLayer(params, useMsgpack);

  const serverInfo = buildServerURL(asyncapi, params.server);
  const reconnect = params.reconnect !== 'false';
  const yieldUndecodable = params?.undecodableMessages !== 'drop';
  setAllowNameCollisions(params?.allowNameCollisions);
  setPerspective(params?.perspective);
  // A client with nothing to send gets no send(_:) (its outgoing type has no cases).
  const canSend = extractMessages(asyncapi).some(m => clientDirection(m.direction) === 'outgoing');
  const msgpackSerializer = prefixedName('MessagePackSerializer');
  const jsonSerializer = prefixedName('JSONMessageSerializer');
  const content = renderSocket({
    names: {
      connState: prefixedName('ConnectionState'),
      config: prefixedName('ClientConfiguration'),
      client: prefixedName('WebSocketClient'),
      error: prefixedName('WebSocketClientError'),
      policyProto: prefixedName('ReconnectionPolicy'),
      backoffPolicy: prefixedName('ExponentialBackoffPolicy'),
      noPolicy: prefixedName('NoReconnectionPolicy'),
      serializerProto: prefixedName('MessageSerializer'),
      incoming: prefixedName('IncomingMessage'),
      outgoing: prefixedName('OutgoingMessage'),
    },
    generic: false,
    defaultUrl: serverInfo ? serverInfo.url : null,
    defaultSerializer: useMsgpack ? `${msgpackSerializer}()` : `${jsonSerializer}()`,
    frame: useMsgpack ? 'data' : 'string',
    undecodable: yieldUndecodable ? 'yield' : 'drop',
    reconnect,
    canSend,
  });
  return { path: 'Sources/WebSocketClient.swift', content };
}

/**
 * The shared client, for a helpers module (lib/helpers.js): generic over a spec's incoming
 * and outgoing messages, with the frame kind decided by the serializer and undecodable
 * messages by the spec's incoming type.
 */
function renderSharedSocket() {
  return renderSocket({
    names: {
      connState: 'ConnectionState',
      config: 'WebSocketClientConfiguration',
      client: 'WebSocketClient',
      error: 'WebSocketClientError',
      policyProto: 'ReconnectionPolicy',
      backoffPolicy: 'ExponentialBackoffPolicy',
      noPolicy: 'NoReconnectionPolicy',
      serializerProto: 'MessageSerializer',
      incoming: 'IncomingMessage',
      outgoing: 'OutgoingMessage',
    },
    generic: true,
    defaultUrl: null,
    defaultSerializer: null,
    frame: 'serializer',
    undecodable: 'protocol',
    reconnect: true,
    canSend: true,
  });
}

/**
 * A spec's own socket file when the shared helpers live in another module: its old names as
 * aliases of the shared types (so code written against an inline client keeps compiling), and
 * a configuration initializer with the spec's serializer.
 */
function renderSpecLayer(params, useMsgpack) {
  const p = (name) => prefixedName(name);
  const incoming = p('IncomingMessage');
  const outgoing = p('OutgoingMessage');
  const serializer = useMsgpack ? 'MessagePackSerializer()' : 'JSONMessageSerializer()';
  // The shared client always has reconnection; reconnect=false makes this spec's default not to.
  const defaultPolicy = params.reconnect === 'false' ? 'NoReconnectionPolicy()' : 'ExponentialBackoffPolicy()';
  const lines = [];
  lines.push('// Generated by asyncapi-swift-ws-template — do not edit');
  lines.push('import Foundation');
  lines.push(`import ${params.helpersModule}`);
  if (useMsgpack) lines.push(`import ${params.messagePackHelpersModule}`);
  lines.push('');
  // Qualified, so an alias without a prefix doesn't refer to itself. Code that imports this module
  // gets every name, as from an inline client.
  const helpers = params.helpersModule;
  for (const name of ['ConnectionState', 'ReconnectionPolicy', 'ExponentialBackoffPolicy', 'NoReconnectionPolicy', 'WebSocketClientError']) {
    lines.push(`public typealias ${p(name)} = ${helpers}.${name}`);
  }
  lines.push(`public typealias ${p('ClientConfiguration')} = ${helpers}.WebSocketClientConfiguration<${incoming}, ${outgoing}>`);
  lines.push(`public typealias ${p('WebSocketClient')} = ${helpers}.WebSocketClient<${incoming}, ${outgoing}>`);
  lines.push('');
  lines.push(`extension WebSocketClientConfiguration where IncomingMessage == ${incoming}, OutgoingMessage == ${outgoing} {`);
  lines.push(`    /// A configuration with this spec's serializer (\`${serializer}\`). To use your own, pass`);
  lines.push('    /// `serializer:` to the shared initializer.');
  lines.push('    public init(');
  lines.push('        url: URL,');
  lines.push('        headers: [String: String] = [:],');
  lines.push(`        reconnectionPolicy: ReconnectionPolicy = ${defaultPolicy},`);
  lines.push('        pingInterval: TimeInterval? = 30.0,');
  lines.push('        onConnected: (@Sendable () async -> Void)? = nil');
  lines.push('    ) {');
  lines.push(`        self.init(url: url, headers: headers, serializer: ${serializer}, reconnectionPolicy: reconnectionPolicy, pingInterval: pingInterval, onConnected: onConnected)`);
  lines.push('    }');
  lines.push('}');
  return { path: 'Sources/WebSocketClient.swift', content: lines.join('\n') + '\n' };
}

function renderSocket(o) {
  const { connState: connStateName, config: configName, client: clientName, error: errorName,
    policyProto, backoffPolicy, noPolicy, serializerProto,
    incoming: incomingName, outgoing: outgoingName } = o.names;
  const reconnect = o.reconnect;
  const genericParams = 'IncomingMessage: IncomingWebSocketMessage, OutgoingMessage: Encodable & Sendable';
  const configType = o.generic ? `${configName}<IncomingMessage, OutgoingMessage>` : configName;

  const lines = [];
  lines.push('// Generated by asyncapi-swift-ws-template — do not edit');
  lines.push('import Foundation');
  lines.push('');

  // ── ConnectionState ──
  lines.push('/// Represents the state of the WebSocket connection.');
  lines.push(`public enum ${connStateName}: Sendable, Equatable {`);
  lines.push('    case disconnected');
  lines.push('    case connecting');
  lines.push('    case connected');
  if (reconnect) {
    lines.push('    case reconnecting(attempt: Int)');
  }
  lines.push('}');
  lines.push('');

  // ── ReconnectionPolicy ──
  if (reconnect) {
    lines.push('/// Strategy controlling whether and when a lost connection is retried.');
    lines.push('///');
    lines.push('/// Inject a custom policy to override the default exponential backoff, or use');
    lines.push(`/// \`${noPolicy}\` to disable automatic reconnection and drive it yourself.`);
    lines.push(`public protocol ${policyProto}: Sendable {`);
    lines.push('    /// Delay before the given 1-based reconnect attempt, or `nil` to stop retrying.');
    lines.push('    func delay(forAttempt attempt: Int) -> TimeInterval?');
    lines.push('}');
    lines.push('');
    lines.push('/// Exponential backoff with jitter (the default reconnection policy).');
    lines.push(`public struct ${backoffPolicy}: ${policyProto} {`);
    lines.push('    public let base: TimeInterval');
    lines.push('    public let maxDelay: TimeInterval');
    lines.push('    public let maxAttempts: Int');
    lines.push('    public let jitter: ClosedRange<Double>');
    lines.push('');
    lines.push('    public init(');
    lines.push('        base: TimeInterval = 1.0,');
    lines.push('        maxDelay: TimeInterval = 60.0,');
    lines.push('        maxAttempts: Int = 10,');
    lines.push('        jitter: ClosedRange<Double> = 0.8...1.2');
    lines.push('    ) {');
    lines.push('        self.base = base');
    lines.push('        self.maxDelay = maxDelay');
    lines.push('        self.maxAttempts = maxAttempts');
    lines.push('        self.jitter = jitter');
    lines.push('    }');
    lines.push('');
    lines.push('    public func delay(forAttempt attempt: Int) -> TimeInterval? {');
    lines.push('        guard attempt <= maxAttempts else { return nil }');
    lines.push('        let raw = base * pow(2.0, Double(attempt - 1))');
    lines.push('        return min(raw, maxDelay) * Double.random(in: jitter)');
    lines.push('    }');
    lines.push('}');
    lines.push('');
    lines.push('/// A policy that never reconnects. Use to fully own reconnection in the caller.');
    lines.push(`public struct ${noPolicy}: ${policyProto} {`);
    lines.push('    public init() {}');
    lines.push('    public func delay(forAttempt attempt: Int) -> TimeInterval? { nil }');
    lines.push('}');
    lines.push('');
  }

  if (o.generic) {
    lines.push('/// The messages a client receives. A message whose payload fails to decode becomes the');
    lines.push('/// value `message(undecodable:error:)` returns, or goes to the `errors` stream when it');
    lines.push('/// returns nil.');
    lines.push('public protocol IncomingWebSocketMessage: Decodable, Sendable {');
    lines.push('    static func message(undecodable data: Data, error: any Error) -> Self?');
    lines.push('    /// The plain-text message a raw text frame is, matched before decoding; nil for none.');
    lines.push('    static func message(text: String) -> Self?');
    lines.push('}');
    lines.push('');
    lines.push('extension IncomingWebSocketMessage {');
    lines.push('    public static func message(text: String) -> Self? { nil }');
    lines.push('}');
    lines.push('');
    lines.push('/// A message that can go out as raw text (a `text/plain` message) instead of the');
    lines.push('/// serializer\'s encoding.');
    lines.push('public protocol TextWebSocketMessage {');
    lines.push('    /// The raw text to send, or nil to send the serializer\'s encoding.');
    lines.push('    var text: String? { get }');
    lines.push('}');
    lines.push('');
  }

  // ── Configuration ──
  lines.push('/// Configuration for the WebSocket client.');
  if (o.generic) {
    lines.push('///');
    lines.push('/// The message types tie a configuration to its client; each spec module adds an');
    lines.push('/// initializer that supplies its serializer.');
    lines.push(`public struct ${configName}<${genericParams}>: Sendable {`);
  } else {
    lines.push(`public struct ${configName}: Sendable {`);
  }
  lines.push('    public let url: URL');
  lines.push('    public let headers: [String: String]');
  lines.push(`    public let serializer: ${serializerProto}`);
  if (reconnect) {
    lines.push(`    public let reconnectionPolicy: ${policyProto}`);
  }
  lines.push('    public let pingInterval: TimeInterval?');
  lines.push('    /// Called each time a socket opens, the first and after every reconnect. Use it to');
  lines.push('    /// authenticate and subscribe, so subscriptions come back after a reconnect without');
  lines.push('    /// the caller tracking the connection state. Messages can arrive while it runs.');
  lines.push('    public let onConnected: (@Sendable () async -> Void)?');
  lines.push('');
  lines.push('    public init(');
  lines.push(`        url: URL${o.defaultUrl ? ` = URL(string: "${swiftStringEscape(o.defaultUrl)}")!` : ''},`);
  lines.push('        headers: [String: String] = [:],');
  lines.push(`        serializer: ${serializerProto}${o.defaultSerializer ? ` = ${o.defaultSerializer}` : ''},`);
  if (reconnect) {
    lines.push(`        reconnectionPolicy: ${policyProto} = ${backoffPolicy}(),`);
  }
  lines.push('        pingInterval: TimeInterval? = 30.0,');
  lines.push('        onConnected: (@Sendable () async -> Void)? = nil');
  lines.push('    ) {');
  lines.push('        self.url = url');
  lines.push('        self.headers = headers');
  lines.push('        self.serializer = serializer');
  if (reconnect) {
    lines.push('        self.reconnectionPolicy = reconnectionPolicy');
  }
  lines.push('        self.pingInterval = pingInterval');
  lines.push('        self.onConnected = onConnected');
  lines.push('    }');
  lines.push('}');
  lines.push('');

  // ── WebSocketClient actor ──
  lines.push('/// Actor-based WebSocket client with typed message send/receive.');
  lines.push(o.generic ? `public actor ${clientName}<${genericParams}> {` : `public actor ${clientName} {`);
  lines.push(`    private let configuration: ${configType}`);
  lines.push('    /// Made on the first connect, with a delegate that reports when each socket opens.');
  lines.push('    private var session: URLSession?');
  lines.push('    private var webSocketTask: URLSessionWebSocketTask?');
  lines.push('    private var receiveTask: Task<Void, Never>?');
  lines.push('    private var pingTask: Task<Void, Never>?');
  if (reconnect) {
    lines.push('    private var reconnectTask: Task<Void, Never>?');
    lines.push('    /// Attempts since the last socket that opened.');
    lines.push('    private var reconnectAttempt = 0');
    lines.push('    private var intentionalDisconnect = false');
  }
  lines.push('');
  lines.push(`    private var messageContinuation: AsyncStream<${incomingName}>.Continuation?`);
  lines.push(`    private var stateContinuation: AsyncStream<${connStateName}>.Continuation?`);
  lines.push('    private var errorContinuation: AsyncStream<any Error>.Continuation?');
  lines.push('');
  lines.push('    /// Stream of incoming messages from the server.');
  lines.push(`    public let messages: AsyncStream<${incomingName}>`);
  lines.push('    /// Stream of connection state changes.');
  lines.push(`    public let connectionState: AsyncStream<${connStateName}>`);
  lines.push('    /// Stream of non-fatal errors: connection drops, ping failures, and — unless the');
  lines.push('    /// undecodable message case is enabled — decode failures.');
  lines.push('    public let errors: AsyncStream<any Error>');
  lines.push('');
  lines.push(`    private var _currentState: ${connStateName} = .disconnected {`);
  lines.push('        didSet { stateContinuation?.yield(_currentState) }');
  lines.push('    }');
  lines.push('');

  // init
  lines.push(o.generic ? `    public init(configuration: ${configType}) {` : `    public init(configuration: ${configName} = ${configName}()) {`);
  lines.push('        self.configuration = configuration');
  lines.push('');
  lines.push(`        var msgCont: AsyncStream<${incomingName}>.Continuation!`);
  lines.push('        self.messages = AsyncStream { msgCont = $0 }');
  lines.push('        self.messageContinuation = msgCont');
  lines.push('');
  lines.push(`        var stateCont: AsyncStream<${connStateName}>.Continuation!`);
  lines.push('        self.connectionState = AsyncStream { stateCont = $0 }');
  lines.push('        self.stateContinuation = stateCont');
  lines.push('');
  lines.push('        var errCont: AsyncStream<any Error>.Continuation!');
  lines.push('        self.errors = AsyncStream { errCont = $0 }');
  lines.push('        self.errorContinuation = errCont');
  lines.push('    }');
  lines.push('');

  // connect
  lines.push('    /// Connect to the WebSocket server, closing any socket this client already has. The');
  lines.push('    /// state is `.connecting` until the socket opens, then `.connected`.');
  lines.push('    public func connect() {');
  if (reconnect) {
    lines.push('        reconnectTask?.cancel()');
    lines.push('        reconnectTask = nil');
    lines.push('        reconnectAttempt = 0');
    lines.push('        intentionalDisconnect = false');
  }
  lines.push('        _currentState = .connecting');
  lines.push('        openSocket()');
  lines.push('    }');
  lines.push('');
  lines.push('    private func openSocket() {');
  lines.push('        closeSocket()');
  lines.push('        var request = URLRequest(url: configuration.url)');
  lines.push('        for (key, value) in configuration.headers {');
  lines.push('            request.setValue(value, forHTTPHeaderField: key)');
  lines.push('        }');
  lines.push('        let task = (session ?? makeSession()).webSocketTask(with: request)');
  lines.push('        webSocketTask = task');
  lines.push('        task.resume()');
  lines.push('        startReceiving(task)');
  lines.push('        startPinging(task)');
  lines.push('    }');
  lines.push('');
  lines.push('    private func makeSession() -> URLSession {');
  lines.push('        let delegate = SocketOpenDelegate { [weak self] taskIdentifier in');
  lines.push('            Task { await self?.socketDidOpen(taskIdentifier) }');
  lines.push('        }');
  lines.push('        let session = URLSession(configuration: .default, delegate: delegate, delegateQueue: nil)');
  lines.push('        self.session = session');
  lines.push('        return session');
  lines.push('    }');
  lines.push('');
  lines.push('    /// Stops the current socket and its loops, without changing the state.');
  lines.push('    private func closeSocket() {');
  lines.push('        receiveTask?.cancel()');
  lines.push('        receiveTask = nil');
  lines.push('        pingTask?.cancel()');
  lines.push('        pingTask = nil');
  lines.push('        webSocketTask?.cancel(with: .normalClosure, reason: nil)');
  lines.push('        webSocketTask = nil');
  lines.push('    }');
  lines.push('');
  lines.push('    /// The socket\'s opening handshake finished: it\'s connected, a reconnect starts again');
  lines.push('    /// from its first attempt, and the onConnected hook runs (to authenticate and');
  lines.push('    /// subscribe, including on a server that sends nothing until then).');
  lines.push('    private func socketDidOpen(_ taskIdentifier: Int) {');
  lines.push('        guard webSocketTask?.taskIdentifier == taskIdentifier else { return }');
  lines.push('        _currentState = .connected');
  if (reconnect) {
    lines.push('        reconnectAttempt = 0');
  }
  lines.push('        if let onConnected = configuration.onConnected {');
  lines.push('            Task { await onConnected() }');
  lines.push('        }');
  lines.push('    }');
  lines.push('');

  // disconnect
  lines.push('    /// Disconnect from the WebSocket server.');
  lines.push('    public func disconnect() {');
  if (reconnect) {
    lines.push('        intentionalDisconnect = true');
    lines.push('        reconnectTask?.cancel()');
    lines.push('        reconnectTask = nil');
  }
  lines.push('        closeSocket()');
  lines.push('        _currentState = .disconnected');
  lines.push('    }');
  lines.push('');

  // send
  if (o.canSend) {
  lines.push('    /// Send a typed message to the server.');
  lines.push(`    public func send(_ message: ${outgoingName}) async throws {`);
  lines.push('        guard let task = webSocketTask else {');
  lines.push(`            throw ${errorName}.notConnected`);
  lines.push('        }');
  lines.push(o.generic
    ? '        if let text = (message as? any TextWebSocketMessage)?.text {'
    : '        if let text = message.text {');
  lines.push('            try await task.send(.string(text))');
  lines.push('            return');
  lines.push('        }');
  lines.push('        let data = try configuration.serializer.encode(message)');
  if (o.frame === 'data') {
    lines.push('        try await task.send(.data(data))');
  } else if (o.frame === 'string') {
    lines.push('        let string = String(data: data, encoding: .utf8) ?? ""');
    lines.push('        try await task.send(.string(string))');
  } else {
    lines.push('        try await task.send(configuration.serializer.frame(for: data))');
  }
  lines.push('    }');
  lines.push('');
  }

  // startReceiving
  lines.push('    private func startReceiving(_ task: URLSessionWebSocketTask) {');
  lines.push('        receiveTask = Task { [weak self] in');
  lines.push('            await self?.receiveLoop(task)');
  lines.push('        }');
  lines.push('    }');
  lines.push('');

  lines.push('    /// Receives from one socket until it closes. A socket this client has since replaced');
  lines.push('    /// delivers nothing more and doesn\'t affect the state.');
  lines.push('    private func receiveLoop(_ task: URLSessionWebSocketTask) async {');
  lines.push('        while !Task.isCancelled {');
  lines.push('            do {');
  lines.push('                let message = try await task.receive()');
  lines.push('                guard task === webSocketTask else { return }');
  lines.push('                let data: Data');
  lines.push('                switch message {');
  lines.push('                case .string(let text):');
  lines.push(`                    if let plain = ${incomingName}.message(text: text) {`);
  lines.push('                        messageContinuation?.yield(plain)');
  lines.push('                        continue');
  lines.push('                    }');
  lines.push('                    data = Data(text.utf8)');
  lines.push('                case .data(let binary):');
  lines.push('                    data = binary');
  lines.push('                @unknown default:');
  lines.push('                    continue');
  lines.push('                }');
  lines.push('                do {');
  lines.push(`                    let incoming = try configuration.serializer.decode(${incomingName}.self, from: data)`);
  lines.push('                    messageContinuation?.yield(incoming)');
  lines.push('                } catch {');
  if (o.undecodable === 'yield') {
    lines.push(`                    messageContinuation?.yield(.undecodable(data, error))`);
  } else if (o.undecodable === 'drop') {
    lines.push('                    errorContinuation?.yield(error)');
  } else {
    lines.push(`                    if let message = ${incomingName}.message(undecodable: data, error: error) {`);
    lines.push('                        messageContinuation?.yield(message)');
    lines.push('                    } else {');
    lines.push('                        errorContinuation?.yield(error)');
    lines.push('                    }');
  }
  lines.push('                }');
  lines.push('            } catch {');
  lines.push('                guard task === webSocketTask else { return }');
  lines.push('                errorContinuation?.yield(error)');
  lines.push('                break');
  lines.push('            }');
  lines.push('        }');
  lines.push('        guard task === webSocketTask else { return }');
  lines.push('        socketDidClose()');
  lines.push('    }');
  lines.push('');
  lines.push('    /// The current socket closed without `disconnect()`.');
  lines.push('    private func socketDidClose() {');
  lines.push('        pingTask?.cancel()');
  lines.push('        pingTask = nil');
  lines.push('        receiveTask = nil');
  lines.push('        webSocketTask = nil');
  if (reconnect) {
    lines.push('        guard !intentionalDisconnect else { return }');
    lines.push('        scheduleReconnect()');
  } else {
    lines.push('        _currentState = .disconnected');
  }
  lines.push('    }');
  lines.push('');

  // startPinging
  lines.push('    private func startPinging(_ task: URLSessionWebSocketTask) {');
  lines.push('        guard let interval = configuration.pingInterval else { return }');
  lines.push('        pingTask = Task { [weak self] in');
  lines.push('            while !Task.isCancelled {');
  lines.push('                try? await Task.sleep(for: .seconds(interval))');
  lines.push('                guard !Task.isCancelled, let self else { break }');
  lines.push('                task.sendPing { error in');
  lines.push('                    if error != nil { Task { await self.handlePingFailure(task) } }');
  lines.push('                }');
  lines.push('            }');
  lines.push('        }');
  lines.push('    }');
  lines.push('');
  lines.push('    /// Surface a ping failure and close the dead socket, so the receive loop ends and the');
  lines.push(reconnect ? '    /// client reconnects.' : '    /// client reports `.disconnected`.');
  lines.push('    private func handlePingFailure(_ task: URLSessionWebSocketTask) {');
  lines.push('        guard task === webSocketTask else { return }');
  lines.push(`        errorContinuation?.yield(${errorName}.pingFailed)`);
  lines.push('        task.cancel(with: .abnormalClosure, reason: nil)');
  lines.push('    }');

  // reconnect logic
  if (reconnect) {
    lines.push('');
    lines.push('    /// Waits for the policy\'s delay, then opens a new socket. Attempts count up until a');
    lines.push('    /// socket opens, so the backoff grows and the policy can give up.');
    lines.push('    private func scheduleReconnect() {');
    lines.push('        let attempt = reconnectAttempt + 1');
    lines.push('        guard let delay = configuration.reconnectionPolicy.delay(forAttempt: attempt) else {');
    lines.push('            _currentState = .disconnected');
    lines.push('            return');
    lines.push('        }');
    lines.push('        reconnectAttempt = attempt');
    lines.push('        _currentState = .reconnecting(attempt: attempt)');
    lines.push('        reconnectTask = Task { [weak self] in');
    lines.push('            try? await Task.sleep(for: .seconds(delay))');
    lines.push('            guard !Task.isCancelled else { return }');
    lines.push('            await self?.reconnect()');
    lines.push('        }');
    lines.push('    }');
    lines.push('');
    lines.push('    private func reconnect() {');
    lines.push('        reconnectTask = nil');
    lines.push('        guard !intentionalDisconnect else { return }');
    lines.push('        openSocket()');
    lines.push('    }');
  }

  lines.push('');
  lines.push('    deinit {');
  lines.push('        receiveTask?.cancel()');
  lines.push('        pingTask?.cancel()');
  if (reconnect) {
    lines.push('        reconnectTask?.cancel()');
  }
  lines.push('        webSocketTask?.cancel(with: .normalClosure, reason: nil)');
  lines.push('        // A session keeps its delegate until it\'s invalidated.');
  lines.push('        session?.invalidateAndCancel()');
  lines.push('    }');
  lines.push('}');
  lines.push('');

  // Open callback
  lines.push('/// Reports each socket\'s finished opening handshake to its client.');
  lines.push('private final class SocketOpenDelegate: NSObject, URLSessionWebSocketDelegate, Sendable {');
  lines.push('    private let didOpen: @Sendable (Int) -> Void');
  lines.push('');
  lines.push('    init(didOpen: @escaping @Sendable (Int) -> Void) {');
  lines.push('        self.didOpen = didOpen');
  lines.push('    }');
  lines.push('');
  lines.push('    func urlSession(_ session: URLSession, webSocketTask: URLSessionWebSocketTask, didOpenWithProtocol protocol: String?) {');
  lines.push('        didOpen(webSocketTask.taskIdentifier)');
  lines.push('    }');
  lines.push('}');
  lines.push('');

  // Error enum
  lines.push(`/// Errors surfaced by ${clientName}.`);
  lines.push(`public enum ${errorName}: Swift.Error, Sendable {`);
  lines.push('    case notConnected');
  lines.push('    case pingFailed');
  lines.push('}');

  return (lines.join('\n')) + '\n';
}

