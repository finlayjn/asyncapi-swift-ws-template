// lib/MessageEnums.js — Generates IncomingMessage and OutgoingMessage tagged enums

const { toSwiftEnumCase, toSwiftPropertyName, prefixedName, setTypePrefix, setAllowNameCollisions, setPerspective, clientDirection, swiftStringEscape } = require('../helpers/swift');
const { extractMessages, chooseDiscriminator, chooseArrayTags, schemaToPlain } = require('../helpers/schema');
const { jsonSchemaTypeToSwift } = require('../helpers/swift');

/**
 * The Swift type an array message's items decode as: the struct of the message whose payload is
 * the same schema (so a frame of several `book` payloads holds the `book` message's type), else
 * the items' own type.
 */
function arrayItemType(msg, allMessages) {
  const itemsId = msg.arrayItems && typeof msg.arrayItems.id === 'function' ? msg.arrayItems.id() : null;
  const owner = itemsId && allMessages.find(m =>
    m !== msg && m.hasObjectPayload && m.payload && typeof m.payload.id === 'function' && m.payload.id() === itemsId);
  if (owner) return owner.swiftName;
  return jsonSchemaTypeToSwift(schemaToPlain(msg.arrayItems), true, msg.messageName);
}

/** A message case's associated type: its struct, an array of its items, or the text. */
function caseType(msg, allMessages) {
  if (msg.hasObjectPayload) return msg.swiftName;
  if (msg.arrayItems) return `[${arrayItemType(msg, allMessages)}]`;
  return 'String';
}

/** The strings a plain message matches: its `const` or `enum` values, else its name. */
function plainLabels(msg, taken) {
  const labels = (msg.textValues || [msg.messageName]).filter(v => !taken.has(v));
  for (const v of labels) taken.add(v);
  return labels.map(v => `"${swiftStringEscape(v)}"`).join(', ');
}

function MessageEnums({ asyncapi, params }) {
  setTypePrefix(params?.typePrefix);
  setAllowNameCollisions(params?.allowNameCollisions);
  setPerspective(params?.perspective);
  const useMsgpack = params?.serialization === 'msgpack';
  const msgpackArray = useMsgpack && params?.msgpackFormat === 'array';
  const yieldUndecodable = params?.undecodableMessages !== 'drop';
  const allMessages = extractMessages(asyncapi);

  const sendMessages = allMessages.filter(m => clientDirection(m.direction) === 'outgoing');
  const receiveMessages = allMessages.filter(m => clientDirection(m.direction) === 'incoming');

  const outgoingName = prefixedName('OutgoingMessage');
  const incomingName = prefixedName('IncomingMessage');

  const helpersModule = params?.helpersModule;
  const lines = [];
  lines.push('// Generated by asyncapi-swift-ws-template — do not edit');
  lines.push('import Foundation');
  if (helpersModule) lines.push(`import ${helpersModule}`);
  lines.push('');

  // ── OutgoingMessage ──
  if (sendMessages.length > 0) {
    lines.push('/// Messages the client can send to the server.');
    lines.push(`public enum ${outgoingName}: Sendable {`);
    for (const msg of sendMessages) {
      const caseName = toSwiftEnumCase(msg.messageName);
      const doc = msg.summary || msg.title;
      if (doc) lines.push(`    /// ${doc.split('\n')[0]}`);
      lines.push(`    case ${caseName}(${caseType(msg, allMessages)})`);
    }
    lines.push('}');
    lines.push('');

    // Encodable conformance
    lines.push(`extension ${outgoingName}: Encodable {`);
    lines.push('    public func encode(to encoder: Encoder) throws {');
    lines.push('        switch self {');
    for (const msg of sendMessages) {
      const caseName = toSwiftEnumCase(msg.messageName);
      if (msg.hasObjectPayload) {
        lines.push(`        case .${caseName}(let value):`);
        lines.push('            try value.encode(to: encoder)');
      } else {
        lines.push(`        case .${caseName}(let value):`);
        lines.push('            var container = encoder.singleValueContainer()');
        lines.push('            try container.encode(value)');
      }
    }
    lines.push('        }');
    lines.push('    }');
    lines.push('}');
    lines.push('');

    // Plain-text messages go out as their raw text, not as the serializer's encoding of it.
    const textSends = sendMessages.filter(m => m.isText);
    lines.push(`extension ${outgoingName}${helpersModule ? ': TextWebSocketMessage' : ''} {`);
    lines.push('    /// The raw text a plain-text message is sent as; nil for one the serializer encodes.');
    if (textSends.length === 0) {
      lines.push('    public var text: String? { nil }');
    } else {
      lines.push('    public var text: String? {');
      lines.push('        switch self {');
      for (const msg of textSends) {
        lines.push(`        case .${toSwiftEnumCase(msg.messageName)}(let value): value`);
      }
      if (textSends.length < sendMessages.length) lines.push('        default: nil');
      lines.push('        }');
      lines.push('    }');
    }
    lines.push('}');
    lines.push('');
  } else {
    // A spec the client only receives on: nothing to send, but the client still names the type.
    lines.push('/// Messages the client can send to the server: none in this spec.');
    lines.push(`public enum ${outgoingName}: Sendable {}`);
    lines.push('');
    lines.push(`extension ${outgoingName}: Encodable {`);
    lines.push('    public func encode(to encoder: Encoder) throws {}');
    lines.push('}');
    lines.push('');
    lines.push(`extension ${outgoingName}${helpersModule ? ': TextWebSocketMessage' : ''} {`);
    lines.push('    public var text: String? { nil }');
    lines.push('}');
    lines.push('');
  }

  // ── IncomingMessage ──
  if (receiveMessages.length > 0) {
    // Separate object-payload messages from plain-value messages for decoding strategy
    const objectReceive = receiveMessages.filter(m => m.hasObjectPayload);
    const arrayReceive = receiveMessages.filter(m => !m.hasObjectPayload && m.arrayItems);
    const plainReceive = receiveMessages.filter(m => !m.hasObjectPayload && !m.arrayItems);
    if (msgpackArray && arrayReceive.length > 0) {
      throw new Error(
        `${incomingName}: ${arrayReceive.map(m => `"${m.messageName}"`).join(', ')} ` +
        `${arrayReceive.length > 1 ? 'have' : 'has'} an array payload, which can't be told apart from a ` +
        `positional MessagePack message (msgpackFormat=array).`
      );
    }

    lines.push('/// Messages the client can receive from the server.');
    lines.push(`public enum ${incomingName}: Sendable {`);
    for (const msg of receiveMessages) {
      const caseName = toSwiftEnumCase(msg.messageName);
      const doc = msg.summary || msg.title;
      if (doc) lines.push(`    /// ${doc.split('\n')[0]}`);
      lines.push(`    case ${caseName}(${caseType(msg, allMessages)})`);
    }
    lines.push('    /// A message whose discriminator did not match any known type.');
    lines.push('    case unknown(String)');
    if (yieldUndecodable) {
      lines.push('    /// A message whose payload failed to decode, with the raw bytes and the decode error.');
      lines.push('    case undecodable(Data, any Error)');
    }
    lines.push('}');
    lines.push('');

    // Decodable conformance — discriminated on detected const field for object messages,
    // plain string matching for non-object messages
    lines.push(`extension ${incomingName}: Decodable {`);

    if (msgpackArray && objectReceive.length > 0) {
      // Each message's first element, its tag
      const { values: discriminatorValues } = chooseArrayTags(objectReceive, incomingName);
      // ── Msgpack array-format decoding ──
      // Server sends events as positional arrays, not keyed maps.
      // Decode discriminator (first element) via unkeyedContainer, then
      // forward the container to the struct's init(from:inout UnkeyedDecodingContainer).

      lines.push('    public init(from decoder: Decoder) throws {');

      if (plainReceive.length > 0) {
        lines.push('        // Array-format discriminated decoding (msgpack)');
        lines.push('        // Try unkeyed container first; plain string messages fall through to catch.');
        lines.push('        do {');
        lines.push('            var container = try decoder.unkeyedContainer()');
        lines.push('            let type = try container.decode(String.self)');
        lines.push('');
        lines.push('            switch type {');
        for (const msg of objectReceive) {
          const caseName = toSwiftEnumCase(msg.messageName);
          const constVal = discriminatorValues.get(msg.messageName);
          lines.push(`            case "${swiftStringEscape(constVal)}":`);
          lines.push(`                self = .${caseName}(try ${msg.swiftName}(from: &container))`);
        }
        lines.push('            default:');
        lines.push('                self = .unknown(type)');
        lines.push('            }');
        lines.push('        } catch {');
        lines.push('            // Plain string messages (no array structure)');
        lines.push('            let container = try decoder.singleValueContainer()');
        lines.push('            let value = try container.decode(String.self)');
        lines.push('            switch value {');
        const taken = new Set();
        for (const msg of plainReceive) {
          const caseName = toSwiftEnumCase(msg.messageName);
          const labels = plainLabels(msg, taken);
          if (!labels) continue;
          lines.push(`            case ${labels}:`);
          lines.push(`                self = .${caseName}(value)`);
        }
        lines.push('            default:');
        lines.push('                self = .unknown(value)');
        lines.push('            }');
        lines.push('        }');
        lines.push('    }');
      } else {
        lines.push('        // Array-format discriminated decoding (msgpack)');
        lines.push('        var container = try decoder.unkeyedContainer()');
        lines.push('        let type = try container.decode(String.self)');
        lines.push('');
        lines.push('        switch type {');
        for (const msg of objectReceive) {
          const caseName = toSwiftEnumCase(msg.messageName);
          const constVal = discriminatorValues.get(msg.messageName);
          lines.push(`        case "${swiftStringEscape(constVal)}":`);
          lines.push(`            self = .${caseName}(try ${msg.swiftName}(from: &container))`);
        }
        lines.push('        default:');
        lines.push('            self = .unknown(type)');
        lines.push('        }');
        lines.push('    }');
      }
    } else {
      // ── Standard keyed-container decoding (JSON / maps) ──

      // The key that tells object messages apart, and each one's value for it
      const { key: discriminatorKey, values: discriminatorValues } = chooseDiscriminator(objectReceive, incomingName);
      // Convert to camelCase for Swift CodingKey case name (without keyword escaping)
      const swiftKeyName = discriminatorKey
        .split(/[^A-Za-z0-9]+/)
        .filter(Boolean)
        .map((word, i) => i === 0 ? word.toLowerCase() : word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
        .join('');

      if (objectReceive.length > 0) {
        lines.push('    private enum TypeKey: String, CodingKey {');
        if (swiftKeyName !== discriminatorKey) {
          lines.push(`        case ${swiftKeyName} = "${swiftStringEscape(discriminatorKey)}"`);
        } else {
          lines.push(`        case ${swiftKeyName}`);
        }
        lines.push('    }');
        lines.push('');
      }
      lines.push('    public init(from decoder: Decoder) throws {');
      if (arrayReceive.length > 0) {
        lines.push(`        // A frame that's an array: ${arrayReceive.map(m => m.messageName).join(', ')}.`);
        lines.push('        if (try? decoder.unkeyedContainer()) != nil {');
        arrayReceive.forEach((msg, i) => {
          const caseName = toSwiftEnumCase(msg.messageName);
          const type = caseType(msg, allMessages);
          if (i < arrayReceive.length - 1) {
            lines.push(`            if let value = try? ${type}(from: decoder) {`);
            lines.push(`                self = .${caseName}(value)`);
            lines.push('                return');
            lines.push('            }');
          } else {
            lines.push(`            self = .${caseName}(try ${type}(from: decoder))`);
            lines.push('            return');
          }
        });
        lines.push('        }');
        lines.push('');
      }

      if (plainReceive.length > 0 && objectReceive.length > 0) {
        // Try keyed container first (common case); plain string messages fall through to catch.
        lines.push('        do {');
        lines.push('            let container = try decoder.container(keyedBy: TypeKey.self)');
        lines.push(`            let type = try container.decode(String.self, forKey: .${swiftKeyName})`);
        lines.push('');
        lines.push('            switch type {');
        for (const msg of objectReceive) {
          const caseName = toSwiftEnumCase(msg.messageName);
          const constVal = discriminatorValues.get(msg.messageName);
          lines.push(`            case "${swiftStringEscape(constVal)}":`);
          lines.push(`                self = .${caseName}(try ${msg.swiftName}(from: decoder))`);
        }
        lines.push('            default:');
        lines.push('                self = .unknown(type)');
        lines.push('            }');
        lines.push('        } catch {');
        lines.push('            // Plain string messages (no keyed structure)');
        lines.push('            let container = try decoder.singleValueContainer()');
        lines.push('            let value = try container.decode(String.self)');
        lines.push('            switch value {');
        const taken = new Set();
        for (const msg of plainReceive) {
          const caseName = toSwiftEnumCase(msg.messageName);
          const labels = plainLabels(msg, taken);
          if (!labels) continue;
          lines.push(`            case ${labels}:`);
          lines.push(`                self = .${caseName}(value)`);
        }
        lines.push('            default:');
        lines.push('                self = .unknown(value)');
        lines.push('            }');
        lines.push('        }');
      } else if (objectReceive.length > 0) {
        lines.push('        let container = try decoder.container(keyedBy: TypeKey.self)');
        lines.push(`        let type = try container.decode(String.self, forKey: .${swiftKeyName})`);
        lines.push('');
        lines.push('        switch type {');
        for (const msg of objectReceive) {
          const caseName = toSwiftEnumCase(msg.messageName);
          const constVal = discriminatorValues.get(msg.messageName);
          lines.push(`        case "${swiftStringEscape(constVal)}":`);
          lines.push(`            self = .${caseName}(try ${msg.swiftName}(from: decoder))`);
        }
        lines.push('        default:');
        lines.push('            self = .unknown(type)');
        lines.push('        }');
      } else {
        lines.push('        let container = try decoder.singleValueContainer()');
        lines.push('        let value = try container.decode(String.self)');
        lines.push('        switch value {');
        const taken = new Set();
        for (const msg of plainReceive) {
          const caseName = toSwiftEnumCase(msg.messageName);
          const labels = plainLabels(msg, taken);
          if (!labels) continue;
          lines.push(`        case ${labels}:`);
          lines.push(`            self = .${caseName}(value)`);
        }
        lines.push('        default:');
        lines.push('            self = .unknown(value)');
        lines.push('        }');
      }
      lines.push('    }');
    }
    lines.push('}');

    // A text frame that is one of the plain-text messages, matched before any decoding.
    const textReceive = receiveMessages.filter(m => m.isText && m.textValues);
    lines.push('');
    lines.push(`extension ${incomingName} {`);
    lines.push('    /// The plain-text message a raw text frame is, or nil when it is none of them.');
    if (textReceive.length === 0) {
      lines.push('    public static func message(text: String) -> Self? { nil }');
    } else {
      lines.push('    public static func message(text: String) -> Self? {');
      lines.push('        switch text {');
      const taken = new Set();
      for (const msg of textReceive) {
        const labels = plainLabels(msg, taken);
        if (labels) lines.push(`        case ${labels}: .${toSwiftEnumCase(msg.messageName)}(text)`);
      }
      lines.push('        default: nil');
      lines.push('        }');
      lines.push('    }');
    }
    lines.push('}');

    // With shared helpers, the generic client reaches undecodable messages through this.
    if (helpersModule) {
      lines.push('');
      lines.push(`extension ${incomingName}: IncomingWebSocketMessage {`);
      lines.push('    public static func message(undecodable data: Data, error: any Error) -> Self? {');
      lines.push(yieldUndecodable ? '        .undecodable(data, error)' : '        nil');
      lines.push('    }');
      lines.push('}');
    }
  } else {
    // A spec the client only sends on: whatever arrives is unknown.
    lines.push('/// Messages the client can receive from the server: none in this spec, so any that');
    lines.push('/// arrives is `unknown`.');
    lines.push(`public enum ${incomingName}: Sendable {`);
    lines.push('    /// A message this spec doesn\'t describe, as text when it is text.');
    lines.push('    case unknown(String)');
    if (yieldUndecodable) {
      lines.push('    /// A message that couldn\'t be read at all, with the raw bytes and the error.');
      lines.push('    case undecodable(Data, any Error)');
    }
    lines.push('}');
    lines.push('');
    lines.push(`extension ${incomingName}: Decodable {`);
    lines.push('    public init(from decoder: Decoder) throws {');
    lines.push('        let container = try decoder.singleValueContainer()');
    lines.push('        self = .unknown((try? container.decode(String.self)) ?? "")');
    lines.push('    }');
    lines.push('}');
    lines.push('');
    lines.push(`extension ${incomingName} {`);
    lines.push('    public static func message(text: String) -> Self? { nil }');
    lines.push('}');
    if (helpersModule) {
      lines.push('');
      lines.push(`extension ${incomingName}: IncomingWebSocketMessage {`);
      lines.push('    public static func message(undecodable data: Data, error: any Error) -> Self? {');
      lines.push(yieldUndecodable ? '        .undecodable(data, error)' : '        nil');
      lines.push('    }');
      lines.push('}');
    }
  }

  return { path: 'Sources/MessageEnums.swift', content: (lines.join('\n')) + '\n' };
}

module.exports = MessageEnums;
