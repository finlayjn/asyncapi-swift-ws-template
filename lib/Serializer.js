// lib/Serializer.js — Generates MessageSerializer protocol and implementations

const { prefixedName, setTypePrefix, setAllowNameCollisions } = require('../helpers/swift');
const { extractEnums } = require('../helpers/schema');

function Serializer({ asyncapi, params }) {
  setTypePrefix(params?.typePrefix);
  setAllowNameCollisions(params?.allowNameCollisions);
  const useMsgpack = params.serialization === 'msgpack';
  if (params?.helpersModule) return renderSpecAliases(params, useMsgpack);
  const protocolName = prefixedName('MessageSerializer');
  const jsonName = prefixedName('JSONMessageSerializer');
  const msgpackName = prefixedName('MessagePackSerializer');
  // The handler lives in Enums.swift, which only exists when the spec has enums
  const openEnums = (params?.openEnums === 'true' || params?.openEnums === true) && extractEnums(asyncapi).length > 0;
  const reporterName = prefixedName('UnknownEnumValue');
  const handlerType = `${reporterName}.Handler`;

  const lines = [];
  lines.push('// Generated by asyncapi-swift-ws-template — do not edit');
  lines.push('import Foundation');
  if (useMsgpack) {
    lines.push('import MessagePack');
  }
  lines.push('');

  // Protocol
  lines.push('/// Abstraction over wire serialization format.');
  lines.push(`public protocol ${protocolName}: Sendable {`);
  lines.push('    func encode<T: Encodable>(_ value: T) throws -> Data');
  lines.push('    func decode<T: Decodable>(_ type: T.Type, from data: Data) throws -> T');
  lines.push('}');
  lines.push('');

  // JSON implementation
  lines.push('/// JSON serializer using Foundation JSONEncoder/JSONDecoder.');
  lines.push(`public struct ${jsonName}: ${protocolName} {`);
  lines.push('    private let encoder = JSONEncoder()');
  if (openEnums) {
    lines.push('    private let decoder: JSONDecoder');
    lines.push('');
    lines.push('    /// - Parameter unknownEnumValueHandler: Called for each enum value the client doesn\'t know.');
    lines.push(`    public init(unknownEnumValueHandler: ${handlerType}? = nil) {`);
    lines.push('        let decoder = JSONDecoder()');
    lines.push(`        if let unknownEnumValueHandler { decoder.userInfo[${reporterName}.handlerKey] = unknownEnumValueHandler }`);
    lines.push('        self.decoder = decoder');
    lines.push('    }');
  } else {
    lines.push('    private let decoder = JSONDecoder()');
    lines.push('');
    lines.push('    public init() {}');
  }
  lines.push('');
  lines.push('    public func encode<T: Encodable>(_ value: T) throws -> Data {');
  lines.push('        try encoder.encode(value)');
  lines.push('    }');
  lines.push('');
  lines.push('    public func decode<T: Decodable>(_ type: T.Type, from data: Data) throws -> T {');
  lines.push('        try decoder.decode(type, from: data)');
  lines.push('    }');
  lines.push('}');

  // MessagePack implementation
  if (useMsgpack) {
    lines.push('');
    lines.push('/// MessagePack serializer using msgpack-swift.');
    lines.push(`public struct ${msgpackName}: ${protocolName} {`);
    if (openEnums) {
      lines.push(`    private let unknownEnumValueHandler: ${handlerType}?`);
      lines.push('');
      lines.push('    /// - Parameter unknownEnumValueHandler: Called for each enum value the client doesn\'t know.');
      lines.push(`    public init(unknownEnumValueHandler: ${handlerType}? = nil) {`);
      lines.push('        self.unknownEnumValueHandler = unknownEnumValueHandler');
      lines.push('    }');
    } else {
      lines.push('    public init() {}');
    }
    lines.push('');
    lines.push('    public func encode<T: Encodable>(_ value: T) throws -> Data {');
    lines.push('        try MessagePackEncoder().encode(value)');
    lines.push('    }');
    lines.push('');
    lines.push('    public func decode<T: Decodable>(_ type: T.Type, from data: Data) throws -> T {');
    if (openEnums) {
      lines.push('        var decoder = MessagePackDecoder()');
      lines.push(`        if let unknownEnumValueHandler { decoder.userInfo[${reporterName}.handlerKey] = unknownEnumValueHandler }`);
      lines.push('        return try decoder.decode(type, from: data)');
    } else {
      lines.push('        try MessagePackDecoder().decode(type, from: data)');
    }
    lines.push('    }');
    lines.push('}');
  }

  return { path: 'Sources/MessageSerializer.swift', content: (lines.join('\n')) + '\n' };
}

/** A spec's serializer names as aliases of the shared helpers' types. */
function renderSpecAliases(params, useMsgpack) {
  const lines = [];
  lines.push('// Generated by asyncapi-swift-ws-template — do not edit');
  lines.push('import Foundation');
  lines.push(`import ${params.helpersModule}`);
  if (useMsgpack) lines.push(`import ${params.messagePackHelpersModule}`);
  lines.push('');
  lines.push(`public typealias ${prefixedName('MessageSerializer')} = MessageSerializer`);
  lines.push(`public typealias ${prefixedName('JSONMessageSerializer')} = JSONMessageSerializer`);
  if (useMsgpack) lines.push(`public typealias ${prefixedName('MessagePackSerializer')} = MessagePackSerializer`);
  lines.push(`public typealias ${prefixedName('UnknownEnumValue')} = UnknownEnumValue`);
  return { path: 'Sources/MessageSerializer.swift', content: (lines.join('\n')) + '\n' };
}

/** The shared serializer protocol and the JSON serializer, for a helpers module. */
function renderSharedSerializer() {
  return `// Generated by asyncapi-swift-ws-template — do not edit
import Foundation

/// Abstraction over wire serialization format.
public protocol MessageSerializer: Sendable {
    func encode<T: Encodable>(_ value: T) throws -> Data
    func decode<T: Decodable>(_ type: T.Type, from data: Data) throws -> T
    /// The socket frame an encoded message is sent as: text by default, binary for formats
    /// that aren't text.
    func frame(for data: Data) -> URLSessionWebSocketTask.Message
}

extension MessageSerializer {
    public func frame(for data: Data) -> URLSessionWebSocketTask.Message {
        .string(String(data: data, encoding: .utf8) ?? "")
    }
}

/// JSON serializer using Foundation JSONEncoder/JSONDecoder.
public struct JSONMessageSerializer: MessageSerializer {
    private let encoder = JSONEncoder()
    private let decoder: JSONDecoder

    /// - Parameter unknownEnumValueHandler: Called for each enum value the client doesn't know.
    public init(unknownEnumValueHandler: UnknownEnumValue.Handler? = nil) {
        let decoder = JSONDecoder()
        if let unknownEnumValueHandler { decoder.userInfo[UnknownEnumValue.handlerKey] = unknownEnumValueHandler }
        self.decoder = decoder
    }

    public func encode<T: Encodable>(_ value: T) throws -> Data {
        try encoder.encode(value)
    }

    public func decode<T: Decodable>(_ type: T.Type, from data: Data) throws -> T {
        try decoder.decode(type, from: data)
    }
}
`;
}

/** The MessagePack serializer, for its own helpers module (so JSON-only clients don't need msgpack-swift). */
function renderSharedMessagePackSerializer(helpersModule) {
  return `// Generated by asyncapi-swift-ws-template — do not edit
import Foundation
import MessagePack
import ${helpersModule}

/// MessagePack serializer using msgpack-swift. Messages go out as binary frames.
public struct MessagePackSerializer: MessageSerializer {
    private let unknownEnumValueHandler: UnknownEnumValue.Handler?

    /// - Parameter unknownEnumValueHandler: Called for each enum value the client doesn't know.
    public init(unknownEnumValueHandler: UnknownEnumValue.Handler? = nil) {
        self.unknownEnumValueHandler = unknownEnumValueHandler
    }

    public func encode<T: Encodable>(_ value: T) throws -> Data {
        try MessagePackEncoder().encode(value)
    }

    public func decode<T: Decodable>(_ type: T.Type, from data: Data) throws -> T {
        var decoder = MessagePackDecoder()
        if let unknownEnumValueHandler { decoder.userInfo[UnknownEnumValue.handlerKey] = unknownEnumValueHandler }
        return try decoder.decode(type, from: data)
    }

    public func frame(for data: Data) -> URLSessionWebSocketTask.Message {
        .data(data)
    }
}
`;
}

module.exports = Serializer;
module.exports.renderSharedSerializer = renderSharedSerializer;
module.exports.renderSharedMessagePackSerializer = renderSharedMessagePackSerializer;
